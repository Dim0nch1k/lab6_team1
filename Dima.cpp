#include <iostream>
using namespace std;

int main() {
    int n;

    // Введення розміру масиву
    cout << "Введіть розмір масиву (не більше 100): ";
    cin >> n;

    if (n <= 0 || n > 100) {
        cout << "Невірний розмір масиву." << endl;
        return 0;
    }

    int A[100]; // масив з максимально можливим розміром

    // Введення елементів масиву
    cout << "Введіть " << n << " елементів масиву:" << endl;
    for (int i = 0; i < n; i++) {
        cin >> A[i];
    }

    // Вивід початкового масиву
    cout << "Початковий масив A: ";
    for (int i = 0; i < n; i++) {
        cout << A[i] << " ";
    }
    cout << endl;

    int k = 0;     // лічильник непарних
    int ind = -1;  // індекс другого непарного елемента

    // Пошук другого непарного
    for (int i = 0; i < n; i++) {
        if (A[i] % 2 != 0) { // непарний
            k++;
            if (k == 2) {
                ind = i;
                break;
            }
        }
    }

    // Перевірка
    if (k < 2) {
        cout << "У масиві менше двох непарних елементів. Роботу завершено." << endl;
        return 0;
    }

    int d = A[ind];

    if (d == 0) {
        cout << "Другий непарний елемент дорівнює 0. Ділення неможливе." << endl;
        return 0;
    }

    // Створення масиву C
    int C[100];
    int m = n - ind; // розмір C
    int j = 0;

    for (int i = ind; i < n; i++) {
        C[j] = A[i] / d;
        j++;
    }

    // Виведення C
    cout << "Масив C: ";
    for (int i = 0; i < m; i++) {
        cout << C[i] << " ";
    }
    cout << endl;

    return 0;
}
